create extension if not exists pgcrypto with schema extensions;

create table if not exists public.cpi_test_codes (
  id bigint generated by default as identity primary key,
  code_hash text not null unique,
  code_display text not null,
  label text not null default '',
  max_uses integer not null default 3 check (max_uses between 1 and 1000),
  used_count integer not null default 0 check (used_count >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.cpi_results (
  id bigint generated by default as identity primary key,
  code_hash text not null,
  score integer not null check (score between 12 and 48),
  cpi integer not null check (cpi between 0 and 100),
  created_at timestamptz not null default now()
);

alter table public.cpi_test_codes enable row level security;
alter table public.cpi_results enable row level security;
revoke all on public.cpi_test_codes, public.cpi_results from anon, authenticated;

create or replace function public.cpi_validate_code(p_code_hash text)
returns table(remaining integer)
language plpgsql
security definer
set search_path = ''
as $$
declare
  code_row public.cpi_test_codes%rowtype;
begin
  select * into code_row
  from public.cpi_test_codes
  where code_hash = p_code_hash and active = true
  for update;

  if not found then
    raise exception '密码无效或已停用' using errcode = 'P0001';
  end if;
  if code_row.used_count >= code_row.max_uses then
    raise exception '此密码的测评次数已用完' using errcode = 'P0001';
  end if;

  update public.cpi_test_codes
  set used_count = used_count + 1
  where id = code_row.id;

  return query select code_row.max_uses - code_row.used_count - 1;
end;
$$;

revoke all on function public.cpi_validate_code(text) from public, anon, authenticated;
grant execute on function public.cpi_validate_code(text) to service_role;

-- Example test code: CPI-START-2026 (three attempts).
insert into public.cpi_test_codes(code_hash, code_display, label, max_uses)
values (encode(extensions.digest('CPI-START-2026', 'sha256'), 'hex'), 'CPI-START-2026', '示例测试密码', 3)
on conflict (code_hash) do nothing;
